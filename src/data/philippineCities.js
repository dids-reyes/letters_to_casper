/**
 * Resolves which Philippine Island Group (luzon, visayas, mindanao) a location belongs to.
 * Returns null if location is international or cannot be determined.
 * @param {string} rawCity
 * @param {string} rawRegion
 * @param {string} rawCountry
 * @returns {'luzon'|'visayas'|'mindanao'|null}
 */
export const getPhilippineIslandGroup = (rawCity = "", rawRegion = "", rawCountry = "") => {
  // If explicitly international, not in the Philippines
  if (isInternationalLocation(rawCity, rawCountry, rawRegion)) {
    return null;
  }

  const cleanCity = String(rawCity || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[.,/#!$%^&*;:{}=\-_~`()]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  const cleanRegion = String(rawRegion || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[.,/#!$%^&*;:{}=\-_~`()]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  const cleanCountry = String(rawCountry || "").trim().toUpperCase();

  // 1. Check cleanRegion first
  if (cleanRegion) {
    if (matchIslandKeyword(cleanRegion, LUZON_IDENTIFIERS)) return "luzon";
    if (matchIslandKeyword(cleanRegion, VISAYAS_IDENTIFIERS)) return "visayas";
    if (matchIslandKeyword(cleanRegion, MINDANAO_IDENTIFIERS)) return "mindanao";
  }

  // 2. Check cleanCity
  if (cleanCity) {
    if (matchIslandKeyword(cleanCity, LUZON_IDENTIFIERS)) return "luzon";
    if (matchIslandKeyword(cleanCity, VISAYAS_IDENTIFIERS)) return "visayas";
    if (matchIslandKeyword(cleanCity, MINDANAO_IDENTIFIERS)) return "mindanao";

    // Check if cleanCity matches a registered Philippine city and resolve via its province
    const reg = PHILIPPINE_CITY_REGISTRY[cleanCity] || (CITY_ALIASES[cleanCity] && PHILIPPINE_CITY_REGISTRY[CITY_ALIASES[cleanCity]]);
    if (reg && reg.province) {
      const prov = reg.province.toLowerCase();
      if (matchIslandKeyword(prov, LUZON_IDENTIFIERS)) return "luzon";
      if (matchIslandKeyword(prov, VISAYAS_IDENTIFIERS)) return "visayas";
      if (matchIslandKeyword(prov, MINDANAO_IDENTIFIERS)) return "mindanao";
    }
  }

  // 3. If explicit Philippine country or general PH location, default to luzon
  if (cleanCountry && PH_COUNTRY_IDENTIFIERS.has(cleanCountry)) {
    return "luzon";
  }
  if (cleanCity === "philippines" || cleanCity === "pilipinas" || cleanRegion === "philippines") {
    return "luzon";
  }

  return null;
};
