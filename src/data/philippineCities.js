/**
 * Normalizes user-inputted city string for fast O(1) lookup
 */
export const normalizeCityName = (rawCity = "") => {
  if (!rawCity || typeof rawCity !== "string") return "";
  let clean = rawCity
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "") // strip accents (e.g. ñ -> n)
    .replace(/[.,/#!$%^&*;:{}=\-_~`()]/g, " ")
    .replace(/\b(city of|city|mun\.|municipality|philippines|ph)\b/g, "")
    .replace(/\s+/g, " ")
    .trim();

  if (CITY_ALIASES[clean]) {
    return CITY_ALIASES[clean];
  }
  return clean;
};

/**
 * Retrieves the philatelic stamp specification for a city
 * @param {string} rawCity - e.g. "Baguio", "Cebu City", "Vigan", "Davao"
 * @returns {object|null} - Philatelic data or null if not in registry
 */
export const getCityStampData = (rawCity = "") => {
  const normalized = normalizeCityName(rawCity);
  if (!normalized) return null;

  // Direct match
  if (PHILIPPINE_CITY_REGISTRY[normalized]) {
    return PHILIPPINE_CITY_REGISTRY[normalized];
  }

  // Alias match
  const aliased = CITY_ALIASES[normalized];
  if (aliased && PHILIPPINE_CITY_REGISTRY[aliased]) {
    return PHILIPPINE_CITY_REGISTRY[aliased];
  }

  // Word-boundary match:
  // 1. If normalized contains full registered city name as word/phrase (e.g. "Baguio Benguet" contains "baguio")
  for (const [key, value] of Object.entries(PHILIPPINE_CITY_REGISTRY)) {
    const regWord = new RegExp(`(^|\\s)${key}(\\s|$)`, "i");
    if (regWord.test(normalized)) {
      return value;
    }
  }

  // 2. If registered city name contains normalized as a distinct word (e.g. "quezon" in "quezon city", but NOT "bali" in "baliwag")
  if (normalized.length >= 3) {
    for (const [key, value] of Object.entries(PHILIPPINE_CITY_REGISTRY)) {
      const regWord = new RegExp(`(^|\\s)${normalized}(\\s|$)`, "i");
      if (regWord.test(key)) {
        return value;
      }
    }
  }

  return null;
};

