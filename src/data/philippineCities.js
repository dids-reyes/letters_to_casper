export const isPhilippineLocation = (cleanCity, cleanRegion, cleanCountry) => {
  if (cleanCountry && PH_COUNTRY_IDENTIFIERS.has(cleanCountry)) return true;
  if (cleanRegion) {
    for (const ph of PH_REGIONS_AND_PROVINCES) {
      if (cleanRegion === ph || cleanRegion.includes(ph)) return true;
    }
  }
  if (cleanCity) {
    const reg = PHILIPPINE_CITY_REGISTRY[cleanCity] || (CITY_ALIASES[cleanCity] && PHILIPPINE_CITY_REGISTRY[CITY_ALIASES[cleanCity]]);
    if (reg && (!reg.country || reg.country === "Philippines")) return true;
    for (const ph of PH_REGIONS_AND_PROVINCES) {
      const regex = new RegExp(`(^|\\s)${ph}(\\s|$)`, "i");
      if (regex.test(cleanCity)) return true;
    }
  }
  return false;
};

/**
 * Determines whether a location is international (outside the Philippines)
 * @param {string} rawCity - e.g. 'Jakarta, Indonesia', 'Ambon', 'Melbourne'
 * @param {string} rawCountry - e.g. 'Indonesia', 'ID', 'US', 'PH'
 * @param {string} rawRegion - e.g. 'Maluku', 'Victoria', 'Central Luzon'
 * @returns {boolean}
 */
export const isInternationalLocation = (rawCity = "", rawCountry = "", rawRegion = "") => {
  const cleanCountry = String(rawCountry || "").trim().toUpperCase();
  const cleanCity = String(rawCity || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[.,/#!$%^&*;:{}=\-_~`()]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  const cleanRegion = String(rawRegion || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[.,/#!$%^&*;:{}=\-_~`()]/g, " ")
    .replace(/\s+/g, " ")
    .trim();

  // 1. If country is provided and is NOT Philippines:
  if (cleanCountry && !PH_COUNTRY_IDENTIFIERS.has(cleanCountry)) {
    return true;
  }

  // 2. If city matches a registered international city:
  if (cleanCity) {
    const reg = PHILIPPINE_CITY_REGISTRY[cleanCity] || (CITY_ALIASES[cleanCity] && PHILIPPINE_CITY_REGISTRY[CITY_ALIASES[cleanCity]]);
    if (reg && reg.country && reg.country !== "Philippines") {
      return true;
    }
  }

  // 3. If any international keyword/country/region is found in city or region:
  for (const kw of INTERNATIONAL_KEYWORDS) {
    const regex = new RegExp(`(^|\\s)${kw}(\\s|$)`, "i");
    if (regex.test(cleanCity) || regex.test(cleanRegion)) {
      return true;
    }
  }

  // 4. If cleanRegion is present and does not match any domestic Philippine region:
  if (cleanRegion) {
    if (isPhilippineLocation(cleanCity, cleanRegion, cleanCountry)) {
      return false; // It's domestic
    }
    return true;
  }

  return false;
};

