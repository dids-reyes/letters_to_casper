export const isPhilippineLocation = (cleanCity, cleanRegion, cleanCountry) => {
  if (cleanCountry && PH_COUNTRY_IDENTIFIERS.has(cleanCountry)) return true;
  if (cleanRegion) {
    for (const ph of PH_REGIONS_AND_PROVINCES) {
      if (cleanRegion === ph || cleanRegion.includes(ph)) return true;
    }
  }
  if (cleanCity) {
    const reg = PHILIPPINE_CITY_REGISTRY[cleanCity] || (CITY_ALIASES[cleanCity] && PHILIPPINE_CITY_REGISTRY[CITY_ALIASES[cleanCity]]);
    if (reg && (!reg.country || reg.country === "Philippines")) return true;
    for (const ph of PH_REGIONS_AND_PROVINCES) {
      const regex = new RegExp(`(^|\\s)${ph}(\\s|$)`, "i");
      if (regex.test(cleanCity)) return true;
    }
  }
  return false;
};

