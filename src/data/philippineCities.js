/**
 * Determines whether a location resolves to one of the dedicated country fallbacks
 * (usa, canada, united_arab_emirates, singapore, malaysia, indonesia, new_zealand)
 * @param {string} rawCity
 * @param {string} rawRegion
 * @param {string} rawCountry
 * @returns {'usa'|'canada'|'united_arab_emirates'|'singapore'|'malaysia'|'indonesia'|'new_zealand'|null}
 */
export const getDedicatedCountryCode = (rawCity = "", rawRegion = "", rawCountry = "") => {
  // If explicitly domestic Philippines, return null
  if (isPhilippineLocation(rawCity, rawRegion, rawCountry)) {
    return null;
  }

  const cleanCountry = String(rawCountry || "").trim().toUpperCase();
  const cleanCity = String(rawCity || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[.,/#!$%^&*;:{}=\-_~`()]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  const cleanRegion = String(rawRegion || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[.,/#!$%^&*;:{}=\-_~`()]/g, " ")
    .replace(/\s+/g, " ")
    .trim();

  // 1. Direct Country Check
  if (cleanCountry) {
    if (cleanCountry === "USA" || cleanCountry === "US" || cleanCountry === "UNITED STATES" || cleanCountry === "UNITED STATES OF AMERICA") return "usa";
    if (cleanCountry === "CANADA" || cleanCountry === "CAN") return "canada";
    if (cleanCountry === "UNITED ARAB EMIRATES" || cleanCountry === "UAE" || cleanCountry === "ARE") return "united_arab_emirates";
    if (cleanCountry === "SINGAPORE" || cleanCountry === "SG" || cleanCountry === "SGP") return "singapore";
    if (cleanCountry === "MALAYSIA" || cleanCountry === "MY" || cleanCountry === "MYS") return "malaysia";
    if (cleanCountry === "INDONESIA" || cleanCountry === "ID" || cleanCountry === "IDN" || cleanCountry === "INA") return "indonesia";
    if (cleanCountry === "NEW ZEALAND" || cleanCountry === "NZ" || cleanCountry === "NZL" || cleanCountry === "AOTEAROA") return "new_zealand";
  }

  // 2. Region (State / Province / Emirate) Check
  if (cleanRegion) {
    if (USA_STATE_CODES.has(cleanRegion)) return "usa";
    for (const kw of USA_IDENTIFIERS) {
      if (cleanRegion === kw || new RegExp(`(^|\\s)${kw}(\\s|$)`, "i").test(cleanRegion)) return "usa";
    }

    if (CANADA_PROVINCE_CODES.has(cleanRegion)) return "canada";
    for (const kw of CANADA_IDENTIFIERS) {
      if (cleanRegion === kw || new RegExp(`(^|\\s)${kw}(\\s|$)`, "i").test(cleanRegion)) return "canada";
    }

    for (const kw of UAE_IDENTIFIERS) {
      if (cleanRegion === kw || new RegExp(`(^|\\s)${kw}(\\s|$)`, "i").test(cleanRegion)) return "united_arab_emirates";
    }
    for (const kw of SINGAPORE_IDENTIFIERS) {
      if (cleanRegion === kw || new RegExp(`(^|\\s)${kw}(\\s|$)`, "i").test(cleanRegion)) return "singapore";
    }
    for (const kw of MALAYSIA_IDENTIFIERS) {
      if (cleanRegion === kw || new RegExp(`(^|\\s)${kw}(\\s|$)`, "i").test(cleanRegion)) return "malaysia";
    }
    for (const kw of INDONESIA_IDENTIFIERS) {
      if (cleanRegion === kw || new RegExp(`(^|\\s)${kw}(\\s|$)`, "i").test(cleanRegion)) return "indonesia";
    }
    for (const kw of NEW_ZEALAND_IDENTIFIERS) {
      if (cleanRegion === kw || new RegExp(`(^|\\s)${kw}(\\s|$)`, "i").test(cleanRegion)) return "new_zealand";
    }
  }

  // 3. City Text Check (e.g. "Los Angeles, CA", "Miami, USA", "Vancouver, Canada", "Bali")
  if (cleanCity) {
    for (const kw of USA_IDENTIFIERS) {
      if (cleanCity === kw || new RegExp(`(^|\\s)${kw}(\\s|$)`, "i").test(cleanCity)) return "usa";
    }
    for (const kw of CANADA_IDENTIFIERS) {
      if (cleanCity === kw || new RegExp(`(^|\\s)${kw}(\\s|$)`, "i").test(cleanCity)) return "canada";
    }
    for (const kw of UAE_IDENTIFIERS) {
      if (cleanCity === kw || new RegExp(`(^|\\s)${kw}(\\s|$)`, "i").test(cleanCity)) return "united_arab_emirates";
    }
    for (const kw of SINGAPORE_IDENTIFIERS) {
      if (cleanCity === kw || new RegExp(`(^|\\s)${kw}(\\s|$)`, "i").test(cleanCity)) return "singapore";
    }
    for (const kw of MALAYSIA_IDENTIFIERS) {
      if (cleanCity === kw || new RegExp(`(^|\\s)${kw}(\\s|$)`, "i").test(cleanCity)) return "malaysia";
    }
    for (const kw of INDONESIA_IDENTIFIERS) {
      if (cleanCity === kw || new RegExp(`(^|\\s)${kw}(\\s|$)`, "i").test(cleanCity)) return "indonesia";
    }
    for (const kw of NEW_ZEALAND_IDENTIFIERS) {
      if (cleanCity === kw || new RegExp(`(^|\\s)${kw}(\\s|$)`, "i").test(cleanCity)) return "new_zealand";
    }
  }

  return null;
};

/**
 * Determines whether a location is within Indonesia
 * Checks city, region, and country parameters flexibly.
 * @param {string} rawCity
 * @param {string} rawRegion
 * @param {string} rawCountry
 * @returns {boolean}
 */
export const isIndonesiaLocation = (rawCity = "", rawRegion = "", rawCountry = "") => {
  const inputs = [rawCity, rawRegion, rawCountry].map((val) => String(val || "").trim());

  // 1. Direct country match
  for (const val of inputs) {
    const upper = val.toUpperCase();
    if (upper === "INDONESIA" || upper === "ID" || upper === "IDN" || upper === "INA") {
      return true;
    }
  }

  // 2. Keyword match against normalized city, region, and country
  const normalizedInputs = inputs.map((val) =>
    val
      .toLowerCase()
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .replace(/[.,/#!$%^&*;:{}=\-_~`()]/g, " ")
      .replace(/\s+/g, " ")
      .trim()
  );

  for (const text of normalizedInputs) {
    if (!text) continue;
    for (const kw of INDONESIA_IDENTIFIERS) {
      if (text === kw) return true;
      const regex = new RegExp(`(^|\\s)${kw}(\\s|$)`, "i");
      if (regex.test(text)) return true;
    }

    // Also check if matches registered city with country: "Indonesia"
    const reg = PHILIPPINE_CITY_REGISTRY[text] || (CITY_ALIASES[text] && PHILIPPINE_CITY_REGISTRY[CITY_ALIASES[text]]);
    if (reg && reg.country === "Indonesia") {
      return true;
    }
  }

  return false;
};

